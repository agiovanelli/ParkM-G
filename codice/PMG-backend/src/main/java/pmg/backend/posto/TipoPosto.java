package pmg.backend.posto;

/**
 * Enum che rappresenta la categoria funzionale assegnata a un posto auto.
 */
public enum TipoPosto {
    /**
     * Posto standard senza riserve specifiche.
     */
    NORMALE,
    /**
     * Posto riservato a persone con disabilità.
     */
    DISABILI,
    /**
     * Posto riservato a donne in gravidanza.
     */
    INCINTA
}
